export const DEFAULT_FONT = 'Caveat_400Regular';

export function findFontOption(fontFamily: string): FontOption | undefined {
  return FONT_OPTIONS.find((f) => f.regular === fontFamily || f.bold === fontFamily);
}

export function canUseBold(fontFamily: string): boolean {
  const opt = findFontOption(fontFamily);
  return !!opt && opt.bold !== opt.regular;
}

export function resolveFontFamily(fontFamily: string, bold: boolean): string {
  const opt = findFontOption(fontFamily);
  if (!opt) return fontFamily;
  if (bold && opt.bold !== opt.regular) return opt.bold;
  return opt.regular;
}
